def _get_llm():
    import os
    key = os.environ.get("GLM_API_KEY", "")
    return GLMProvider(api_key=key) if key else None

def _get_engine() -> StageEngine:
    """Build a StageEngine with default stages and empty gates."""
    ede_dir = Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found. Run `ede init` first.")
        raise typer.Exit(code=1)

    db = Persistence(str(ede_dir / "state.db"))
    gates = GateEngine()
    trust = TrustConfig.from_yaml(Path(".ede/config.yaml"))
    engine = StageEngine(db, gates, trust)

    # Register all seven stages with empty gates for MVP
    engine.register_stage(Stage(Phase.SPEC, prerequisites=[], gates=[]))
    engine.register_stage(Stage(Phase.DESIGN, prerequisites=[], gates=[]))
    engine.register_stage(Stage(Phase.PLAN, prerequisites=[], gates=[]))
    llm = _get_llm()
    ctx_engine = ContextEngine(".")
    def _make_run_fn(phase):
        async def _run(task_id, p):
            if llm is None:
                return
            ctx = ctx_engine.resolve()
            sp = GLMProvider.build_system_prompt(ctx)
            msgs = [ChatMessage(role="system", content=sp),
                    ChatMessage(role="user", content=f"Phase: {phase.value}, task: {task_id}")]
            result = await llm.chat(msgs, thinking_budget=thinking_for_phase(phase))
            console.print(f"  [dim]LLM response: {result.output_tokens} tokens[/dim]")
            # Parse and persist change log + change entries
            if result.content and "Change Summary" in result.content:
                ch = parse_change_summary(result.content)
                ch.task_id = task_id
                try:
                    ede_dir = __import__('pathlib').Path('.ede')
                    if ede_dir.exists():
                        pdb = Persistence(str(ede_dir / 'state.db'))
                        pdb.insert_change_log(ch)
                        console.print(f"  [dim]ChangeLog saved: {ch.intent_group.value} / {ch.risk_label.value}[/dim]")
                        entries = parse_change_entries(result.content, ch.change_id)
                        for entry in entries:
                            pdb.insert_change_entry(entry)
                        if entries:
                            console.print(f"  [dim]ChangeEntries saved: {len(entries)} entries[/dim]")
                except Exception:
                    logging.getLogger("ede.cli").warning("Failed to persist ChangeLog/Entries", exc_info=True)
        return _run
    # Register builtin gates and attach to stages
    register_builtin_gates(gates, ".")
    engine.register_stage(Stage(Phase.CODE, prerequisites=[], gates=["lint", "test"], run_fn=_make_run_fn(Phase.CODE)))
    engine.register_stage(Stage(Phase.TEST, prerequisites=[], gates=["test", "coverage"], run_fn=_make_run_fn(Phase.TEST)))
    # Special run_fns for REVIEW (3-parallel reviewers) and MERGE (gate verification)
    def _make_review_fn(phase):
        async def _run(task_id, p):
            if llm is None:
                return
            # 3-way prose review is A-class ceremony; the accuracy reviewer
            # (B-class, ran at CODE) is what has teeth. Skip the 3-way unless T0.
            if trust.effective_tier("review") != "T0":
                console.print("  [dim]3-way review skipped (tier > T0); accuracy reviewer already ran at CODE.[/dim]")
                return
            reviewer_llm = GLMProvider(api_key=llm.api_key, model=llm.model, base_url=llm.base_url)
            orchestrator = ReviewerOrchestrator(reviewer_llm)
            try:
                diff = __import__('subprocess').run(
                    ["git", "diff", "--unified=3"], capture_output=True, text=True, timeout=30
                ).stdout[:4000]
            except Exception:
                diff = "[diff unavailable]"
            spec_text = ctx_engine.resolve()
            report = await orchestrator.review(task_id, spec_text, diff)
            console.print(f"\n  [bold]Review Report[/bold] ({report.total_errors} errors, {report.total_warnings} warnings)")
            for f in report.findings:
                icon = {"error": "[red]X[/red]", "warning": "[yellow]!![/yellow]", "info": "[dim]i[/dim]"}.get(f.severity, "?")
                console.print(f"    {icon} [{f.dimension}] {f.message[:100]}")
            if report.total_errors > 0:
                console.print(f"\n  [bold red]{report.total_errors} errors found — must fix before merge.[/bold red]")
            elif report.total_warnings > 0:
                console.print(f"\n  [yellow]{report.total_warnings} warnings — review before proceeding.[/yellow]")
            else:
                console.print(f"\n  [green]No issues found.[/green]")
            try:
                ede_dir = __import__('pathlib').Path('.ede')
                if ede_dir.exists():
                    pdb = Persistence(str(ede_dir / 'state.db'))
                    pdb.write_audit(task_id, "review_complete", f"Errors:{report.total_errors} Warnings:{report.total_warnings}")
            except Exception:
                pass
        return _run

    def _make_merge_fn(phase):
        async def _run(task_id, p):
            console.print(f"  [bold]Merge check: verifying all gates...[/bold]")
            try:
                ede_dir = __import__('pathlib').Path('.ede')
                if ede_dir.exists():
                    pdb = Persistence(str(ede_dir / 'state.db'))
                    logs = pdb.get_audit_logs(task_id)
                    failed_gates = [l for l in logs if "gates_failed" in l.get("action", "")]
                    if failed_gates:
                        console.print(f"  [red]X[/red] {len(failed_gates)} gate failure(s) in audit log — merge blocked.")
                    else:
                        console.print(f"  [green]OK[/green] All gates passed. Ready to merge.")
                    pdb.write_audit(task_id, "merge_verified", f"Gates checked: {len(logs)} audit entries")
            except Exception:
                console.print(f"  [yellow]!![/yellow] Could not verify gates (no .ede/ directory).")
        return _run

    engine.register_stage(Stage(Phase.REVIEW, prerequisites=[], gates=[], run_fn=_make_review_fn(Phase.REVIEW)))
    engine.register_stage(Stage(Phase.MERGE, prerequisites=[], gates=[], run_fn=_make_merge_fn(Phase.MERGE)))

    # Inject accuracy reviewer for post-code checks
    llm = _get_llm()
    if llm is not None:
        reviewer = ReviewerOrchestrator(llm)
        engine.set_reviewer(reviewer)

    return engine


