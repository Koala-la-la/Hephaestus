@task_app.command("create")
def task_create(
    description: str,
    start_at: str = typer.Option("spec", "--start-at", "-s",
        help="Start at phase: spec, design, plan, code, test, review, merge"),
    depends_on: str = typer.Option("", "--depends-on", "-d",
        help="Task ID that must complete before this one starts"),
) -> None:
    """Create a new task, optionally starting from a later phase."""
    valid = {"spec", "design", "plan", "code", "test", "review", "merge"}
    if start_at not in valid:
        console.print(f"[red]X[/red] Invalid --start-at value: {start_at}. Valid: {', '.join(sorted(valid))}")
        raise typer.Exit(code=1)

    engine = _get_engine()
    task_id = str(uuid.uuid4())[:8]
    project_id = _get_first_project_id(engine.db)
    engine.db.create_task(task_id, project_id, description, start_phase=start_at, depends_on=depends_on)

    phases = ["spec", "design", "plan", "code", "test", "review", "merge"]
    skipped = [p for p in phases if phases.index(p) < phases.index(start_at)]
    for p in skipped:
        engine.db.write_audit(task_id, "phase_skipped", f"Skipped {p} (started at {start_at})")

    tui.render_task_created(task_id, description)
    console.print(f"  Starting at: [bold]{start_at}[/bold]{' (skipped '+', '.join(skipped)+')' if skipped else ''}")
    if depends_on:
        console.print(f"  Depends on: [bold cyan]{depends_on}[/bold cyan]")


@task_app.command("run")
def task_run(task_id: str = "") -> None:
    """Advance the pipeline. Uses the most recent task if task_id not given."""
    engine = _get_engine()
    if not task_id:
        task = engine.db.get_first_task()
        if task is None:
            console.print("[red]X[/red] No tasks found. Run `ede task create` first.")
            raise typer.Exit(code=1)
        task_id = task["task_id"]

    task = engine.db.get_task(task_id)
    if task is None:
        console.print(f"[red]X[/red] Task {task_id} not found.")
        raise typer.Exit(code=1)

    import asyncio; result = asyncio.run(engine.advance(task_id))
    tui.render_pipeline_result(result)


@task_app.command("list")
def task_list() -> None:
    """List all tasks."""
    ede_dir = Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found.")
        raise typer.Exit(code=1)
    db = Persistence(str(ede_dir / "state.db"))
    import sqlite3
    with sqlite3.connect(db.db_path) as conn:
        conn.row_factory = sqlite3.Row
        rows = conn.execute(
            "SELECT task_id, phase, status, depends_on, created_at FROM task ORDER BY created_at"
        ).fetchall()
    if not rows:
        console.print("[dim]No tasks found.[/dim]")
        return
    tbl = Table(title="Tasks")
    tbl.add_column("ID", style="cyan")
    tbl.add_column("Phase", style="yellow")
    tbl.add_column("Status")
    tbl.add_column("Depends On", style="dim")
    tbl.add_column("Created")
    for r in rows:
        tbl.add_row(
            r["task_id"], r["phase"], r["status"],
            r["depends_on"] or "-",
            r["created_at"][:16] if r["created_at"] else "-",
        )
    console.print(tbl)


@app.command("audit")
def audit_show(task_id: str = typer.Argument("", help="Task ID to show audit log for")) -> None:
    """Show audit log with integrity verification."""
    ede_dir = Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found.")
        raise typer.Exit(code=1)
    db = Persistence(str(ede_dir / "state.db"))
    if not task_id:
        task = db.get_first_task()
        if task is None:
            console.print("[yellow]!![/yellow] No tasks found.")
            return
        task_id = task["task_id"]
    logs = db.get_audit_logs(task_id)
    if not logs:
        console.print(f"[dim]No audit entries for {task_id}.[/dim]")
        return
    integrity = db.verify_audit_integrity(task_id)
    if not integrity["valid"]:
        console.print(f"[bold red]!![/bold red] Audit chain BROKEN at id={integrity['broken_at']}!")
    else:
        console.print(f"[green]OK[/green] Audit chain intact ({len(logs)} entries).")
    tbl = Table(title=f"Audit Log — {task_id}")
    tbl.add_column("ID", style="dim")
    tbl.add_column("Action", style="cyan")
    tbl.add_column("Detail")
    tbl.add_column("Hash", style="dim")
    for entry in logs[-20:]:
        tbl.add_row(
            str(entry.get("id", "")),
            entry.get("action", ""),
            (entry.get("detail", "") or "")[:60],
            (entry.get("integrity_hash", "") or "")[:8],
        )
    console.print(tbl)


