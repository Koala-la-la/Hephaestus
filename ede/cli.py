@app.command()
def init(name: str) -> None:
    """Initialize a new EDE project in the current directory."""
    project_id = str(uuid.uuid4())[:8]
    ede_dir = Path(".ede")
    db_path = ede_dir / "state.db"
    context_path = ede_dir / "context.yaml"
    audit_path = ede_dir / "ede_audit.log"

    try:
        ede_dir.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        console.print("[yellow]!![/yellow] .ede/ already exists in this directory.")
        raise typer.Exit(code=1)

    try:
        db = Persistence(str(db_path))
        db.init_db()
    except Exception as e:
        console.print(f"[red]X[/red] Failed to initialize database: {e}")
        raise typer.Exit(code=1)

    context_path.write_text(DEFAULT_CONTEXT_YAML, encoding="utf-8")
    audit_path.write_text(
        f"# EDE Audit Log — project {name} ({project_id})\n"
        f"# Created: {__import__('datetime').datetime.now().isoformat()}\n\n"
    )
    db.insert_project(project_id, name)

    # Generate config.yaml with default trust tier
    config_path = ede_dir / "config.yaml"
    config_path.write_text("""# EDE project config — auto-generated by `ede init`
# Trust tier: T0=conservative, T1=assisted(default), T2=autonomous, T3=full auto
# See spec §8 for details.

trust:
  tier: T1
  overrides: {}
    # merge: T0  # uncomment to require manual merge confirmation
""", encoding="utf-8")

    tui.render_init_summary(project_id, name, str(db_path), str(context_path), str(audit_path))


@app.command()
def status() -> None:
    """Show current project status."""
    ede_dir = Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found. Run `ede init` first.")
        raise typer.Exit(code=1)

    db = Persistence(str(ede_dir / "state.db"))
    tables = db.get_tables()
    if not tables:
        console.print("[yellow]!![/yellow] Database is empty.")
        return

    table = Table(title="EDE Status")
    table.add_column("Table", style="cyan")
    table.add_column("Rows", justify="right")
    for t in tables:
        table.add_row(t, str(db.table_count(t)))
    console.print(table)


