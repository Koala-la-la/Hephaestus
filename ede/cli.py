# ── Helpers ──────────────────────────────────────────

def _get_llm():
    import os
    key = os.environ.get("DEEPSEEK_API_KEY", "")
    return DeepSeekProvider(api_key=key) if key else None

def _get_engine() -> StageEngine:
    """Build a StageEngine with default stages and empty gates."""
    ede_dir = Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found. Run `ede init` first.")
        raise typer.Exit(code=1)

    db = Persistence(str(ede_dir / "state.db"))
    gates = GateEngine()
    trust = TrustConfig.from_yaml(Path(".ede/config.yaml"))
    engine = StageEngine(db, gates, trust)

    # Register all seven stages with empty gates for MVP
    engine.register_stage(Stage(Phase.SPEC, prerequisites=[], gates=[]))
    engine.register_stage(Stage(Phase.DESIGN, prerequisites=[], gates=[]))
    engine.register_stage(Stage(Phase.PLAN, prerequisites=[], gates=[]))
    llm = _get_llm()
    ctx_engine = ContextEngine(".")
    def _make_run_fn(phase):
        def _run(task_id, p):
            if llm is None:
                return
            import asyncio
            ctx = ctx_engine.resolve()
            sp = DeepSeekProvider.build_system_prompt(ctx)
            msgs = [ChatMessage(role="system", content=sp),
                    ChatMessage(role="user", content=f"Phase: {phase.value}, task: {task_id}")]
            try:
                loop = asyncio.get_event_loop()
            except RuntimeError:
                loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
            result = loop.run_until_complete(llm.chat(msgs, thinking_budget=thinking_for_phase(phase)))
            console.print(f"  [dim]LLM response: {result.output_tokens} tokens[/dim]")
            # Parse and persist change log + change entries
            if result.content and "Change Summary" in result.content:
                ch = parse_change_summary(result.content)
                ch.task_id = task_id
                try:
                    ede_dir = __import__('pathlib').Path('.ede')
                    if ede_dir.exists():
                        pdb = Persistence(str(ede_dir / 'state.db'))
                        pdb.insert_change_log(ch)
                        console.print(f"  [dim]ChangeLog saved: {ch.intent_group.value} / {ch.risk_label.value}[/dim]")
                        # Parse and persist per-file change entries
                        entries = parse_change_entries(result.content, ch.change_id)
                        for entry in entries:
                            pdb.insert_change_entry(entry)
                        if entries:
                            console.print(f"  [dim]ChangeEntries saved: {len(entries)} entries[/dim]")
                except Exception:
                    logging.getLogger("ede.cli").warning("Failed to persist ChangeLog/Entries", exc_info=True)
        return _run
    # Register builtin gates and attach to stages
    register_builtin_gates(gates, ".")
    engine.register_stage(Stage(Phase.CODE, prerequisites=[], gates=["lint", "test"], run_fn=_make_run_fn(Phase.CODE)))
    engine.register_stage(Stage(Phase.TEST, prerequisites=[], gates=["test", "coverage"], run_fn=_make_run_fn(Phase.TEST)))
    engine.register_stage(Stage(Phase.REVIEW, prerequisites=[], gates=[], run_fn=_make_run_fn(Phase.REVIEW)))
    engine.register_stage(Stage(Phase.MERGE, prerequisites=[], gates=[], run_fn=_make_run_fn(Phase.MERGE)))

    # Inject accuracy reviewer for post-code checks
    llm = _get_llm()
    if llm is not None:
        reviewer = ReviewerOrchestrator(llm)
        engine.set_reviewer(reviewer)

    return engine


