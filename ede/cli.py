@task_app.command("create")
def task_create(
    description: str,
    start_at: str = typer.Option("spec", "--start-at", "-s",
        help="Start at phase: spec, design, plan, code, test, review, merge"),
) -> None:
    """Create a new task, optionally starting from a later phase."""
    valid = {"spec", "design", "plan", "code", "test", "review", "merge"}
    if start_at not in valid:
        console.print(f"[red]X[/red] Invalid --start-at value: {start_at}. Valid: {', '.join(sorted(valid))}")
        raise typer.Exit(code=1)

    engine = _get_engine()
    task_id = str(uuid.uuid4())[:8]
    project_id = _get_first_project_id(engine.db)
    engine.db.create_task(task_id, project_id, description, start_phase=start_at)

    # Auto-complete audit trail for skipped phases
    phases = ["spec", "design", "plan", "code", "test", "review", "merge"]
    skipped = [p for p in phases if phases.index(p) < phases.index(start_at)]
    for p in skipped:
        engine.db.write_audit(task_id, "phase_skipped", f"Skipped {p} (started at {start_at})")

    tui.render_task_created(task_id, description)
    console.print(f"  Starting at: [bold]{start_at}[/bold]{' (skipped '+', '.join(skipped)+')' if skipped else ''}")


@task_app.command("run")
def task_run(task_id: str = "") -> None:
    """Advance the pipeline. Uses the most recent task if task_id not given."""
    engine = _get_engine()
    if not task_id:
        task = engine.db.get_first_task()
        if task is None:
            console.print("[red]X[/red] No tasks found. Run `ede task create` first.")
            raise typer.Exit(code=1)
        task_id = task["task_id"]

    task = engine.db.get_task(task_id)
    if task is None:
        console.print(f"[red]X[/red] Task {task_id} not found.")
        raise typer.Exit(code=1)

    result = engine.advance(task_id)
    tui.render_pipeline_result(result)


@app.command("confirm")
def confirm(stage: str) -> None:
    """Confirm a human checkpoint (spec, design, or plan)."""
    engine = _get_engine()
    task = engine.db.get_first_task()
    if task is None:
        console.print("[red]X[/red] No tasks found.")
        raise typer.Exit(code=1)

    result = engine.confirm(task["task_id"], stage)
    tui.render_pipeline_result(result)


# ── Helpers ──────────────────────────────────────────

def _get_first_project_id(db: Persistence) -> str:
    """Get the first project id from the database."""
    tables = db.get_tables()
    if "project" in tables:
        with __import__('sqlite3').connect(db.db_path) as conn:
            conn.row_factory = __import__('sqlite3').Row
            row = conn.execute("SELECT project_id FROM project LIMIT 1").fetchone()
            return row["project_id"] if row else "default"
    return "default"






@app.command("dashboard")
def dashboard() -> None:
    """Show interactive project dashboard."""
    ede_dir = __import__("pathlib").Path(".ede")
    if not ede_dir.exists():
        tui.console.print("[red]X[/red] No .ede/ directory found.")
        raise typer.Exit(code=1)

    db = Persistence(str(ede_dir / "state.db"))
    task = db.get_first_task()
    if task is None:
        tui.console.print("[yellow]!![/yellow] No tasks found.")
        return

    # Gather checkpoints and audit logs
    checkpoints = []
    audit_logs = []
    try:
        # Query checkpoints
        import sqlite3
        conn = sqlite3.connect(str(ede_dir / "state.db"))
        conn.row_factory = sqlite3.Row
        rows = conn.execute(
            "SELECT stage, status, confirmed_at FROM checkpoint WHERE task_id=? ORDER BY id",
            (task["task_id"],),
        ).fetchall()
        checkpoints = [dict(r) for r in rows]
        conn.close()
    except Exception:
        logging.getLogger("ede.cli").warning("Failed to query checkpoints", exc_info=True)

    audit_logs = db.get_audit_logs(task["task_id"])

    tui.render_status_dashboard(task, checkpoints, audit_logs)

@app.command("refine")
def refine() -> None:
    """Analyze audit logs and suggest context.yaml improvements."""
    ede_dir = __import__("pathlib").Path(".ede")
    if not ede_dir.exists():
        console.print("[red]X[/red] No .ede/ directory found.")
        raise typer.Exit(code=1)

    db = Persistence(str(ede_dir / "state.db"))
    task = db.get_first_task()
    if task is None:
        console.print("[yellow]!![/yellow] No tasks to analyze.")
        return

    logs = db.get_audit_logs(task["task_id"])
    if not logs:
        console.print("[yellow]!![/yellow] No audit logs found.")
        return

    sr_engine = SelfRefinement(".")
    suggestions = sr_engine.analyze(logs)
    console.print(sr_engine.get_suggestions_summary(suggestions))

    if suggestions:
        result = sr_engine.apply(suggestions)
        console.print(f"  Updated: {result['updated']}, Skipped: {result['skipped']}")


